  /* SYN을 정규화: 모든 단어 소문자화 */
  var GROUPS = SYN.map(function (g) {
    return g.map(function (w) { return String(w).toLowerCase(); });
  });

  function norm(s) { return String(s == null ? '' : s).toLowerCase(); }

  /* 검색어를 공백 단위 토큰으로 분리 */
  function tokenize(query) {
    return norm(query).trim().split(/\s+/).filter(Boolean);
  }

  /* 토큰 하나를 동의어 그룹으로 확장 → 검색할 변형 단어 목록 반환
   *  - 토큰 자신은 항상 포함
   *  - 그룹 멤버와 (2글자 이상에서) 부분일치하면 그룹 전체를 추가 */
  function expandToken(token) {
    var t = norm(token);
    var out = {};
    out[t] = true;
    for (var i = 0; i < GROUPS.length; i++) {
      var g = GROUPS[i];
      var hit = false;
      for (var j = 0; j < g.length; j++) {
        var m = g[j];
        if (m === t) { hit = true; break; }
        if (t.length >= 2 && m.indexOf(t) !== -1) { hit = true; break; }
        if (m.length >= 2 && t.indexOf(m) !== -1) { hit = true; break; }
      }
      if (hit) for (var k = 0; k < g.length; k++) out[g[k]] = true;
    }
    return Object.keys(out);
  }

  /* 검색어 전체의 모든 변형 단어(중복 제거) — 하이라이트용 */
  function allVariants(query) {
    var set = {};
    tokenize(query).forEach(function (t) {
      expandToken(t).forEach(function (v) { set[v] = true; });
    });
    return Object.keys(set);
  }

  /* 핵심: haystack 문자열이 검색어의 모든 토큰을 만족하는가?
   *  - 토큰 간 = AND (모든 단어가 있어야 함)
   *  - 토큰 내부 동의어 = OR (변형 중 하나라도 있으면 됨)
   *  - 검색어가 비어 있으면 true */
  function matchAll(haystack, query) {
    var tokens = tokenize(query);
    if (!tokens.length) return true;
    var hay = norm(haystack);
    if (!hay) return false;
    for (var i = 0; i < tokens.length; i++) {
      var variants = expandToken(tokens[i]);
      var ok = false;
      for (var j = 0; j < variants.length; j++) {
        if (hay.indexOf(variants[j]) !== -1) { ok = true; break; }
      }
      if (!ok) return false;
    }
    return true;
  }

  /* haystack 안에 실제로 등장한 변형 단어들 — 담보 하이라이트용 */
  function termsInText(text, query) {
    var hay = norm(text);
    if (!hay) return [];
    return allVariants(query).filter(function (v) {
      return v && hay.indexOf(v) !== -1;
    });
  }

  /* 텍스트에 검색어 관련 단어가 하나라도 들어있는가? (담보 단위 하이라이트 판정) */
  function touches(text, query) {
    return termsInText(text, query).length > 0;
  }

